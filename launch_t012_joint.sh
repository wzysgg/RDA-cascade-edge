#!/usr/bin/env bash
# T014 joint driver body (TASK s5).
#
#   deploy hash gate -> read-only preflight -> ONE joint concurrent two-arm
#   ~250 s experiment over 4 GPUs -> one shared 60 s drain -> one streaming
#   verify + summarize -> RUN_COMPLETE.json
#
# Self-locating: PROJECT/ENTRY/ART come from this script's own path plus the run
# id, so no historical archive path and no ENTRY=run_t012.py are used.  Every
# stage checks its own rc; only this run's own children and state files are
# touched.
set -uo pipefail

SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT="${T014_PROJECT:-$SELF_DIR}"
RUN_ID="${T014_RUN_ID:-T014}"
PY="${T014_PY:-/home/wangzengyu/edge_paper/environments/torch/bin/python}"
LOCK="${T014_SHARED_LOCK:-/home/wangzengyu/edge_paper/experiments/v20_two_gpu_validation_20261004/.live_two_gpu.lock}"
ENTRY="$PROJECT/run.py"
ART="$PROJECT/results/$RUN_ID"
LOGDIR="$ART/logs"
EVIDENCE="$ART/evidence"
STATE="$LOGDIR/RUN_STATE.json"
RESULT="$LOGDIR/RUN_COMPLETE.json"
FACTS="$LOGDIR/T014_joint_facts.json"
LOG="$LOGDIR/driver.log"
STATUS="$LOGDIR/STATUS.md"
# TASK s5.7: the driver hard wall cap is 900 s (warm-up + 250 s run + <=60 s
# drain); the failure is recorded and cleaned up with a bound past it.
JOINT_WALL_S="${T014_JOINT_WALL_S:-900}"
# TASK s5.2 / s5.6: ONE explicit effective reference address for the factory,
# the runtime and the checks -- the merged copy generated by --prepare-only.
REFERENCE="${T014_REFERENCE_JSON:-$ART/evidence/REFERENCE.json}"
export TASK_REFERENCE_JSON="$REFERENCE"
IMPLEMENTATION_REVISION="$(cd "$PROJECT" && "$PY" -c 'import run_t011; print(run_t011.IMPLEMENTATION_REVISION)')" || exit 8

JOINT_PID=""
JOINT_ATTEMPT_ID=""
DRAIN_BUDGET_OK="false"
JOINT_RC=""
WRAPUP_LOCK_HELD="false"
DRIVER_PID=$$

export OMP_NUM_THREADS=1
export OPENBLAS_NUM_THREADS=1
export MKL_NUM_THREADS=1
export PYTHONUNBUFFERED=1
unset CUDA_VISIBLE_DEVICES

mkdir -p "$LOGDIR"
exec >>"$LOG" 2>&1

utc() { date -u +%Y-%m-%dT%H:%M:%SZ; }
say() { printf '%s T014-driver pid=%s %s\n' "$(utc)" "$DRIVER_PID" "$*"; }

echo "$DRIVER_PID" > "$LOGDIR/driver.pid"
say "driver_start project=$PROJECT run_id=$RUN_ID python=$PY lock=$LOCK entry=$ENTRY"
say "effective_reference=$REFERENCE"

json_string_field() {
  grep -o "\"$2\": *\"[^\"]*\"" "$1" 2>/dev/null | head -n 1 | sed 's/.*: *"//; s/"$//'
}
json_scalar_field() {
  grep -o "\"$2\": *[^,}]*" "$1" 2>/dev/null | head -n 1 | sed 's/.*: *//; s/ *$//'
}

write_state() {
  # $1 status  $2 stage  $3 rc  $4 detail
  printf '{\n'                                              >  "$STATE"
  printf '  "schema": "T014_run_state_v1",\n'                >> "$STATE"
  printf '  "task_id": "%s",\n' "$RUN_ID"                   >> "$STATE"
  printf '  "implementation_revision": "%s",\n' "$IMPLEMENTATION_REVISION" >> "$STATE"
  printf '  "algorithm_revision": "QF-4R",\n'                >> "$STATE"
  printf '  "status": "%s",\n' "$1"                          >> "$STATE"
  printf '  "stage": "%s",\n' "$2"                           >> "$STATE"
  printf '  "rc": %s,\n' "$3"                                >> "$STATE"
  printf '  "driver_pid": %s,\n' "$DRIVER_PID"               >> "$STATE"
  printf '  "joint_pid": "%s",\n' "$JOINT_PID"               >> "$STATE"
  printf '  "joint_rc": "%s",\n' "$JOINT_RC"                 >> "$STATE"
  printf '  "joint_attempt_id": "%s",\n' "$JOINT_ATTEMPT_ID" >> "$STATE"
  printf '  "drain_budget_ok": %s,\n' "$DRAIN_BUDGET_OK"     >> "$STATE"
  printf '  "reference_sha256": "%s",\n' "${TASK_REFERENCE_SHA256:-}" >> "$STATE"
  printf '  "wrapup_lock_held": %s,\n' "$WRAPUP_LOCK_HELD"   >> "$STATE"
  printf '  "utc": "%s",\n' "$(utc)"                         >> "$STATE"
  printf '  "detail": "%s"\n' "$4"                           >> "$STATE"
  printf '}\n'                                               >> "$STATE"
  cp -f "$STATE" "$RESULT"
  printf '%s T014 status=%s stage=%s rc=%s joint_attempt_id=%s drain_budget_ok=%s\n' \
    "$(utc)" "$1" "$2" "$3" "$JOINT_ATTEMPT_ID" "$DRAIN_BUDGET_OK" >> "$STATUS"
}

finish() {
  write_state "$1" "$2" "$3" "${4:-}"
  say "driver_finish status=$1 stage=$2 rc=$3"
  exit "$3"
}

stop_own_children() {
  if [ -z "$JOINT_PID" ]; then
    return 0
  fi
  say "stop_own_children pgid=$JOINT_PID"
  kill -TERM -- "-$JOINT_PID" 2>/dev/null
  sleep 3
  kill -KILL -- "-$JOINT_PID" 2>/dev/null
  return 0
}

acquire_wrapup_lock() {
  if [ -z "${LOCK_FD:-}" ]; then
    exec {LOCK_FD}>"$LOCK" 2>/dev/null
    if [ -z "${LOCK_FD:-}" ]; then
      say "warning: cannot open $LOCK; wrap-up continues unlocked"
      return 1
    fi
  fi
  if flock -n "$LOCK_FD"; then
    WRAPUP_LOCK_HELD="true"
    say "wrapup_lock_acquired path=$LOCK"
    return 0
  fi
  WRAPUP_LOCK_HELD="false"
  say "warning: public lock is held by another process; wrap-up continues unlocked"
  return 1
}

load_facts() {
  if [ ! -f "$FACTS" ]; then
    say "warning: $FACTS missing after --joint-facts"
    return 1
  fi
  local attempt drain
  attempt="$(json_string_field "$FACTS" joint_attempt_id)"
  drain="$(json_scalar_field "$FACTS" drain_budget_ok)"
  if [ -n "$attempt" ]; then
    JOINT_ATTEMPT_ID="$attempt"
  fi
  if [ -n "$drain" ]; then
    DRAIN_BUDGET_OK="$drain"
  fi
  say "joint_facts attempt_id=$JOINT_ATTEMPT_ID drain_budget_ok=$DRAIN_BUDGET_OK"
  return 0
}

dump_environment() {
  say "read-only environment dump"
  nvidia-smi -L 2>&1 | sed 's/^/  nvidia-smi: /'
  nvidia-smi --query-gpu=index,uuid,name,memory.used,utilization.gpu --format=csv 2>&1 |
    sed 's/^/  gpu: /'
  free -m 2>&1 | sed 's/^/  mem: /'
  df -h "$PROJECT" 2>&1 | sed 's/^/  disk: /'
  nproc 2>&1 | sed 's/^/  nproc: /'
  lscpu -p=CPU,CORE,SOCKET,NODE 2>&1 | grep -v '^#' | head -n 48 | sed 's/^/  lscpu: /'
}

# ---- start-up guards ------------------------------------------------------
if [ ! -f "$ENTRY" ]; then
  say "entry point missing: $ENTRY"
  finish failed startup 8 "entry point missing"
fi
if [ ! -f "$REFERENCE" ]; then
  say "effective reference missing: $REFERENCE (run --prepare-only first)"
  finish failed reference_missing 5 "effective reference missing"
fi
if [ -z "${TASK_REFERENCE_SHA256:-}" ]; then
  export TASK_REFERENCE_SHA256="$(sha256sum "$REFERENCE" | awk '{print $1}')"
fi
say "reference_sha256=$TASK_REFERENCE_SHA256"
rm -f "$RESULT" "$STATE"
if ! flock -n "$LOCK" -c true; then
  say "public lock is held by another run: $LOCK"
  finish failed lock_busy 4 "public two-GPU lock held"
fi
OTHER="$(pgrep -a -f 'run.py --run-id .*--joint-run' 2>/dev/null || true)"
if [ -n "$OTHER" ]; then
  say "another joint runner is active:"
  printf '%s\n' "$OTHER"
  finish failed other_runner 3 "another joint runner active"
fi
if [ ! -f "$EVIDENCE/cpu_checks.json" ]; then
  say "missing $EVIDENCE/cpu_checks.json: run --check before the joint run"
  finish failed cpu_checks_missing 5 "cpu_checks.json missing"
fi

dump_environment

# ---- stage 1: per-file deployment hash gate (TASK s5 item 4) --------------
say "stage deploy_audit start"
"$PY" -u "$ENTRY" --run-id "$RUN_ID" --deploy-audit
rc=$?
if [ "$rc" -ne 0 ]; then
  say "stage deploy_audit failed rc=$rc"
  finish failed deploy_audit "$rc" "deployment hash gate failed"
fi
say "stage deploy_audit ok"

# ---- stage 2: read-only preflight (GPU + CPU topology + public lock) ------
say "stage preflight start"
"$PY" -u "$ENTRY" --run-id "$RUN_ID" --preflight
rc=$?
if [ "$rc" -ne 0 ]; then
  say "stage preflight failed rc=$rc (wait for free resources and retry; never fall back to two sequential cards)"
  finish failed preflight "$rc" "preflight failed"
fi
say "stage preflight ok"

# ---- stage 3: the ONE joint run (its own session/process group) -----------
say "stage joint_run start duration_s=250 watchdog_s=$JOINT_WALL_S"
setsid timeout -k 30 "$JOINT_WALL_S" "$PY" -u "$ENTRY" --run-id "$RUN_ID" --joint-run &
JOINT_PID=$!
say "joint_run pid=$JOINT_PID"
wait "$JOINT_PID"
rc=$?
JOINT_RC="$rc"
say "stage joint_run finished rc=$rc"

if [ "$rc" -ne 0 ]; then
  stop_own_children
  acquire_wrapup_lock
  "$PY" -u "$ENTRY" --run-id "$RUN_ID" --joint-facts
  facts_rc=$?
  if [ "$facts_rc" -ne 0 ]; then
    say "warning: --joint-facts failed rc=$facts_rc"
  fi
  load_facts
  finish failed joint_run "$rc" "joint run failed (or watchdog expired); own children stopped, state saved"
fi

# ---- wrap-up: hold the public lock for verify + summarize -----------------
acquire_wrapup_lock
say "stage joint_facts start"
"$PY" -u "$ENTRY" --run-id "$RUN_ID" --joint-facts
rc=$?
if [ "$rc" -ne 0 ]; then
  finish failed joint_facts "$rc" "could not write joint facts"
fi
load_facts

say "stage verify start"
"$PY" -u "$ENTRY" --run-id "$RUN_ID" --verify
rc=$?
if [ "$rc" -ne 0 ]; then
  say "warning: verify failed rc=$rc; summarize still runs on the existing data"
fi
if [ ! -f "$EVIDENCE/verification.json" ]; then
  say "warning: $EVIDENCE/verification.json missing after --verify"
fi

say "stage summarize start"
"$PY" -u "$ENTRY" --run-id "$RUN_ID" --summarize --out "$EVIDENCE/metrics.json"
rc=$?
if [ "$rc" -ne 0 ]; then
  finish failed summarize "$rc" "summarize failed"
fi
if [ ! -f "$EVIDENCE/metrics.json" ]; then
  say "missing $EVIDENCE/metrics.json after --summarize"
  finish failed metrics_missing 1 "metrics.json missing"
fi
say "stage summarize ok"

finish complete done 0 "joint run complete"
